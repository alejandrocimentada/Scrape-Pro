(async function init() {
  await ssI18n.init();
  ssI18n.apply(document);
  const key = `results_${resultId}`;
  data = (await chrome.storage.session.get(key))[key];
  if (!data) {
    document.querySelector('main').replaceChildren(el('p', { className: 'empty', textContent: t('resultsGone') }));
    return;
  }
  const title = data.recipe.title || t('extractedData');
  document.title = `${title} · Scrape Pro`;
  $('title').textContent = title;
  $('meta').replaceChildren(`${t('from')} `, el('a', { href: data.url, target: '_blank', rel: 'noopener', textContent: data.pageTitle || data.url }));
  if (data.request) {
    $('request').textContent = `“${data.request}”`;
    $('request').hidden = false;
  }
  const r = data.recipe;
  $('recipe').textContent = [
    `${t('items')}:  ${r.itemSelector ?? t('wholePage')}`,
    '',
    ...r.fields.map((f) => `${f.name}  ←  ${f.selector ?? t('theItem')}${f.attribute ? `  [${f.attribute}]` : ''}${f.regex ? `  /${f.regex}/` : ''}`),
  ].join('\n');
  render();
})();
