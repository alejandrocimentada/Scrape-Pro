function el(tag, props = {}, ...kids) {
  const node = document.createElement(tag);
  Object.assign(node, props);
  node.append(...kids.filter((k) => k != null));
  return node;
}

function fileBase() {
  const host = new URL(data.url).hostname.replace(/^www\./, '').replace(/[^a-z0-9]+/gi, '-');
  return `${host}-${new Date().toISOString().slice(0, 10)}`;
}

function download(content, filename, type) {
  const a = document.createElement('a');
  a.href = URL.createObjectURL(new Blob([content], { type }));
  a.download = filename;
  a.click();
  setTimeout(() => URL.revokeObjectURL(a.href), 1000);
}

function flash(btn, text = 'Done ✓') {
  const prev = btn.textContent;
  btn.textContent = text;
  btn.classList.add('done');
  setTimeout(() => { btn.textContent = prev; btn.classList.remove('done'); }, 1400);
}

/* ───────────── numbers (for sorting prices like "£1,299.00" or "RD$ 450") ───────────── */
function toNumber(v) {
  let s = String(v).replace(/[^0-9.,-]/g, '');
  const lastComma = s.lastIndexOf(',');
  const lastDot = s.lastIndexOf('.');
  if (lastComma > -1 && lastDot > -1) {
    // Both present: whichever comes last is the decimal separator.
    // "1.299,00" → 1299.00   "1,299.00" → 1299.00
    s = lastComma > lastDot ? s.replace(/\./g, '').replace(',', '.') : s.replace(/,/g, '');
  } else if (lastComma > -1) {
    // Only commas: several, or exactly 3 digits after one, means thousands ("1,299", "1,299,000");
    // otherwise it's a decimal comma ("12,50").
    const commas = (s.match(/,/g) || []).length;
    s = commas > 1 || /,\d{3}$/.test(s) ? s.replace(/,/g, '') : s.replace(',', '.');
  } else if ((s.match(/\./g) || []).length > 1) {
    s = s.replace(/\./g, ''); // "1.299.000" uses dots for thousands
  }
  const n = parseFloat(s);
  return Number.isFinite(n) ? n : null;
}
const looksNumeric = (v) => /^[^\d]{0,5}[\d.,\s-]+[^\d]{0,8}$/.test(String(v).trim());
const isNumericColumn = (col) => {
  const values = data.rows.map((r) => r[col]).filter((v) => v !== '');
  return values.length > 0 && values.every(looksNumeric);
};

/* ───────────── exports ───────────── */
// Spreadsheet apps run cells starting with = + @ as formulas. Scraped text is untrusted, so neutralize them.
const safeCell = (v) => (/^[=+@]|^-(?!\d)/.test(v) ? `'${v}` : v);

function toCSV() {
  const esc = (v) => `"${safeCell(String(v ?? '')).replace(/"/g, '""')}"`;
  const lines = [data.columns.map(esc).join(','), ...view.map((r) => data.columns.map((c) => esc(r[c])).join(','))];
  return '﻿' + lines.join('\r\n'); // BOM so Excel reads UTF-8 (£, €, ñ) correctly
}

function toTSV() {
  const clean = (v) => safeCell(String(v ?? '').replace(/[\t\r\n]+/g, ' '));
  return [data.columns.join('\t'), ...view.map((r) => data.columns.map((c) => clean(r[c])).join('\t'))].join('\n');
}

const py = (v) => (v == null ? 'None' : JSON.stringify(String(v)));

function pythonScript() {
  const r = data.recipe;
  const fields = r.fields
    .map((f) => `    (${py(f.name)}, ${py(f.selector)}, ${py(f.attribute)}, ${py(f.regex)}),`)
    .join('\n');
  return `# pip install requests beautifulsoup4
# Generated by Scrape Pro: ${r.title || data.request || 'extraction'}
# Run it again any time (e.g. daily) to get fresh data in results.csv.
import csv
import re
import sys
from urllib.parse import urljoin

import requests
from bs4 import BeautifulSoup

URL = ${py(data.url)}
ITEM_SELECTOR = ${py(r.itemSelector)}  # None = one row for the whole page
FIELDS = [  # (column, selector inside the item or None, attribute or None for text, regex or None)
${fields}
]


def read(element, selector, attribute, pattern):
    node = element.select_one(selector) if selector else element
    if node is None:
        return ""
    if attribute is None:
        value = " ".join(node.get_text(" ").split())
    else:
        value = node.get(attribute, "")
        if isinstance(value, list):  # BeautifulSoup returns class as a list
            value = " ".join(value)
        if attribute in ("href", "src") and value:
            value = urljoin(URL, value)
    if pattern:
        match = re.search(pattern, value)
        value = (match.group(1) if match.groups() else match.group(0)) if match else ""
    return value


def main():
    response = requests.get(
        URL,
        headers={"User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0 Safari/537.36"},
        timeout=20,
    )
    response.raise_for_status()
    soup = BeautifulSoup(response.content, "html.parser")
    items = soup.select(ITEM_SELECTOR) if ITEM_SELECTOR else [soup]
    if not items:
        sys.exit("No items found. If this page is built with JavaScript, requests can't see it; use a headless browser such as Playwright instead.")

    rows = [{name: read(item, sel, attr, pat) for name, sel, attr, pat in FIELDS} for item in items]
    with open("results.csv", "w", newline="", encoding="utf-8-sig") as f:
        writer = csv.DictWriter(f, fieldnames=[name for name, *_ in FIELDS])
        writer.writeheader()
        writer.writerows(rows)
    print(f"Saved {len(rows)} rows to results.csv")


if __name__ == "__main__":
    main()
`;
}

/* ───────────── table ───────────── */
function render() {
  const q = $('search').value.trim().toLowerCase();
  view = data.rows.filter((r) => !q || data.columns.some((c) => String(r[c]).toLowerCase().includes(q)));

  if (sortCol) {
    const numeric = isNumericColumn(sortCol);
    view.sort((a, b) => {
      if (numeric) return ((toNumber(a[sortCol]) ?? -Infinity) - (toNumber(b[sortCol]) ?? -Infinity)) * sortDir;
      return String(a[sortCol]).localeCompare(String(b[sortCol]), undefined, { numeric: true }) * sortDir;
    });
  }

  $('thead').replaceChildren(el('tr', {},
    el('th', { textContent: '#' }),
    ...data.columns.map((c) => {
      const th = el('th', { textContent: c, title: t('clickToSort') });
      if (c === sortCol) th.append(el('span', { className: 'dir', textContent: sortDir === 1 ? '↑' : '↓' }));
      th.addEventListener('click', () => {
        sortDir = sortCol === c ? -sortDir : 1;
        sortCol = c;
        render();
      });
      return th;
    })));

  const frag = document.createDocumentFragment();
  view.forEach((row, i) => {
    const tr = el('tr', {}, el('td', { className: 'num', textContent: String(i + 1) }));
    for (const c of data.columns) {
      const value = String(row[c] ?? '');
      const td = el('td', { title: value });
      if (!value) {
        td.className = 'empty-cell';
        td.textContent = '—';
      } else if (/^https?:\/\//.test(value)) {
        td.append(el('a', { href: value, target: '_blank', rel: 'noopener', textContent: value }));
      } else {
        td.textContent = value;
      }
      tr.append(td);
    }
    frag.append(tr);
  });
  $('tbody').replaceChildren(frag);
  $('count').textContent = t('showingRows', { shown: view.length, total: data.rows.length, cols: data.columns.length });
}

